import test from 'tape'
import wtf from '../../lib/index.js'

test('Links forwards link accessors', (t) => {
  const links = wtf('[[Toronto|City]] and [[Montreal]].').links()
  t.deepEqual(links.page(), ['Toronto', 'Montreal'], 'page destinations')
  t.deepEqual(links.text(), ['City', 'Montreal'], 'display text')
  t.deepEqual(links.type(), ['internal', 'internal'], 'link types')
  t.deepEqual(links.anchor(), ['', ''], 'missing anchors')
  t.deepEqual(links.href(), ['./Toronto', './Montreal'], 'resolved URLs')
  t.deepEqual(links.wikitext(), ['[[Toronto|City]]', '[[Montreal]]'], 'source markup')
  t.deepEqual(links.wiki(), ['[[Toronto|City]]', '[[Montreal]]'], 'wiki accessor')
  t.equal(links.json('xl')[0].wiki, '[[Toronto|City]]', 'JSON format reaches each link')
  t.notOk(Object.hasOwn(links.json()[0], 'wiki'), 'default JSON omits markup')
  t.end()
})

test('Images forwards filenames, captions, and thumbnail sizes', (t) => {
  const images = wtf('[[File:Example.jpg|thumb|A [[City|city]]]]').images()
  t.deepEqual(images.file(), ['File:Example.jpg'], 'filenames')
  t.deepEqual(images.format(), ['jpg'], 'formats')
  t.deepEqual(images.caption(), ['A city'], 'caption text')
  t.deepEqual(images.thumbnail(80), ['https://wikipedia.org/wiki/Special:Redirect/file/Example.jpg?width=80'], 'thumbnail argument')
  t.deepEqual(images.url(), ['https://wikipedia.org/wiki/Special:Redirect/file/Example.jpg'], 'image URLs')
  t.deepEqual(images.src(), images.url(), 'src aliases url')
  t.deepEqual(images.links()[0].page(), ['City'], 'caption links remain a nested Links collection')
  t.end()
})

test('Lists and Blocks forward methods without flattening results', (t) => {
  const lists = wtf('* [[Alice]]\n* Bob').lists()
  t.deepEqual(lists.text(), [' * Alice\n * Bob'], 'list text stays one result per list')
  t.equal(lists.items().length, 1, 'items remain grouped by list')
  t.deepEqual(lists.items()[0].text(), ['Alice', 'Bob'], 'items are Blocks')
  t.deepEqual(lists.lines()[0].text(), ['Alice', 'Bob'], 'lines also return Blocks')
  t.deepEqual(lists.links()[0].page(), ['Alice'], 'list links are Links')
  const blocks = lists.items()[0]
  t.deepEqual(blocks.links().map((links) => links.page()), [['Alice'], []], 'one Links collection per Block')
  t.deepEqual(blocks.bolds(), [[], []], 'one formatting array per Block')
  t.deepEqual(blocks.italics(), [[], []], 'empty italic arrays retain item boundaries')
  t.equal(blocks.json('xl')[0].text, 'Alice', 'Block JSON is forwarded')
  t.ok(Object.hasOwn(blocks.json('xl')[0], 'wiki'), 'Block JSON format preserves markup')
  t.end()
})

test('Sentences forwards inherited Block methods', (t) => {
  const sentences = wtf("Hello '''Alice''' and ''Bob''.").sentences()
  t.deepEqual(sentences.text(), ['Hello Alice and Bob.'], 'inherited text method')
  t.deepEqual(sentences.bolds().map((spans) => spans.map((span) => span.text)), [['Alice']], 'inherited bolds method')
  t.deepEqual(sentences.italics().map((spans) => spans.map((span) => span.text)), [['Bob']], 'inherited italics method')
  t.deepEqual(sentences.links().map((links) => links.page()), [[]], 'inherited links method')
  t.deepEqual(sentences.interwiki(), [[]], 'sentence-specific method')
  t.deepEqual(sentences.wikitext(), ["Hello '''Alice''' and ''Bob''."], 'inherited wikitext method')
  t.end()
})

test('Infoboxes forwards field arguments and preserves missing results', (t) => {
  const boxes = wtf('{{Infobox person|name=[[Alice]]|First|Second}}\n{{Infobox person|occupation=Writer}}').infoboxes()
  t.deepEqual(boxes.type(), ['person', 'person'], 'infobox type methods')
  t.deepEqual(boxes.get('name').map((block) => block?.text()), ['Alice', undefined], 'missing field keeps its result slot')
  t.deepEqual(boxes.get('list').map((block) => block?.text()), ['First', undefined], 'get returns only the first value')
  t.deepEqual(boxes.getFirst(['name', 'occupation']).map((block) => block?.text()), ['Alice', 'Writer'], 'choice arguments forwarded')
  t.deepEqual(boxes.getAll(['list', 'name']).map((blocks) => blocks.text()), [['First', 'Second', 'Alice'], []], 'all values remain grouped by infobox')
  t.deepEqual(boxes.links().map((links) => links.page()), [['Alice'], []], 'nested Links collections')
  t.end()
})

test('Tables forwards row selection arguments', (t) => {
  const tables = wtf('{| class="wikitable"\n! City\n|-\n| [[Toronto]]\n|}').tables()
  t.deepEqual(tables.cols(), [['city']], 'column names remain grouped by table')
  t.deepEqual(tables.rows(), [[{ city: 'Toronto' }]], 'rows remain grouped by table')
  t.deepEqual(tables.getRows('city'), [['Toronto']], 'string selector')
  t.deepEqual(tables.getRows(['city']), [[['Toronto']]], 'array selector')
  t.deepEqual(tables.getRows({ city: true }), [[{ city: 'Toronto' }]], 'object selector')
  t.deepEqual(tables.getRows(), [[{ city: 'Toronto' }]], 'omitted selector')
  t.deepEqual(tables.headers()[0].text(), ['City'], 'header Blocks')
  t.deepEqual(tables.cells()[0].text(), ['City', 'Toronto'], 'cell Blocks')
  t.deepEqual(tables.links()[0].page(), ['Toronto'], 'table Links')
  t.end()
})

test('Templates and References forward methods but not getters', (t) => {
  const doc = wtf('{{custom example|[[Alice]]}} Text<ref>{{cite web|title=Example|url=https://example.com}}</ref>')
  const templates = doc.templates('custom example')
  t.equal(templates.json()[0].template, 'custom example', 'template JSON')
  t.deepEqual(templates.wikitext(), ['{{custom example|[[Alice]]}}'], 'template source')
  t.deepEqual(templates.links()[0].page(), ['Alice'], 'template Links')
  t.notOk('type' in templates, 'type getter is not a collection method')
  t.notOk('kind' in templates, 'kind getter is not a collection method')
  const references = doc.references()
  t.deepEqual(references.title(), ['Example'], 'reference titles')
  t.deepEqual(doc.citations().title(), ['Example'], 'citations use References')
  t.deepEqual(references.text(), [''], 'reference text method')
  t.ok(Object.hasOwn(references.json('xl')[0], 'wiki'), 'reference JSON format')
  t.notOk('kind' in references, 'reference kind getter is not forwarded')
  t.end()
})

test('empty wrappers expose their specific methods', (t) => {
  const doc = wtf('')
  t.deepEqual(doc.links().href(), [], 'empty Links')
  t.deepEqual(doc.images().thumbnail(80), [], 'empty Images')
  t.deepEqual(doc.lists().items(), [], 'empty Lists')
  t.deepEqual(doc.sentences().bolds(), [], 'empty Sentences')
  t.deepEqual(doc.infoboxes().getAll(['name']), [], 'empty Infoboxes')
  t.deepEqual(doc.tables().getRows('city'), [], 'empty Tables')
  t.deepEqual(doc.templates().wikitext(), [], 'empty Templates')
  t.deepEqual(doc.references().title(), [], 'empty References')
  t.deepEqual(wtf('{{Infobox person|name=Alice}}').infobox().getAll(['missing']).text(), [], 'empty Blocks')
  t.end()
})
