/* eslint-disable no-console */
// merges the fetched data (01-03) with overrides.js and regenerates ../src/data/.
// also cross-checks every name against the core registry, so no alias can clobber it.
import { writeFileSync, existsSync } from 'node:fs'
import { families } from './_config.js'
import { readData, today } from './_lib.js'
import overrides from './overrides.js'
import coreTemplates from '../../../src/templates/index.ts'
import coreAliases from '../../../src/templates/aliases.ts'

const sitelinks = readData('01-sitelinks.json')
const redirects = readData('02-redirects.json')
const paramData = readData('03-params.json')
const srcDir = new URL('../src/data/', import.meta.url)

// 'Modèle:Lien web' → 'lien web'
const strip = (title) => title.replace(/^[^:]+:/, '').toLowerCase().trim()
const esc = (str) => str.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
// single-character names are fine outside ascii ('旗', '門'), never inside it.
// a ':' reads as parser-function syntax, so those names can never match anyway.
const badName = (name) =>
  name.length === 0 || name.length > 60 || (name.length === 1 && /[\x20-\x7e]/.test(name)) || /[|{}=[\]<>#:]/.test(name) || /^\d+$/.test(name)

// every localized name for one family, with the wikis it was seen on
const gather = (fam) => {
  const names = new Map()
  const add = (title, lang) => {
    const name = strip(title)
    if (!names.has(name)) {
      names.set(name, new Set())
    }
    names.get(name).add(lang)
  }
  const pages = (sitelinks[fam] && sitelinks[fam].pages) || {}
  Object.keys(pages).forEach((lang) => pages[lang].forEach((title) => add(title, lang)))
  Object.keys(redirects).forEach((lang) => {
    const list = redirects[lang] ? redirects[lang][fam] : null
    if (lang !== '_fetched' && list) {
      list.forEach((title) => add(title, lang))
    }
  })
  return names
}

const famKeys = Object.keys(families)
const all = {}
famKeys.forEach((fam) => {
  all[fam] = gather(fam)
})

// a name can only serve one family in a flat registry — pin it, or drop it everywhere
const claims = {}
famKeys.forEach((fam) => {
  all[fam].forEach((_langs, name) => {
    claims[name] = claims[name] || []
    claims[name].push(fam)
  })
})
Object.keys(claims)
  .filter((name) => claims[name].length > 1)
  .forEach((name) => {
    const keep = overrides.pin[name]
    claims[name].forEach((fam) => {
      if (fam !== keep) {
        all[fam].delete(name)
      }
    })
    if (!keep) {
      console.log(`⚠️  dropped '${name}' — claimed by ${claims[name].join(' + ')} (pin it in overrides.js to keep)`)
    }
  })

// drop no-ops, junk, excluded names, and anything the core registry already owns
const excluded = new Set(overrides.exclude)
let coreDrops = 0
const keepable = (fam, name) => {
  if (name === fam || badName(name) || excluded.has(name)) {
    return false
  }
  if (coreTemplates[name] !== undefined || coreAliases[name] !== undefined) {
    coreDrops += 1
    return false
  }
  return true
}

// numbered co-author params (nom3→last3 …) triple the map sizes for little value
const trimMap = (found) => {
  const map = {}
  Object.keys(found).forEach((key) => {
    if (/[2-9]$/.test(key) === false && /[2-9]$/.test(found[key]) === false) {
      map[key] = found[key]
    }
  })
  return map
}

// maps are stored once per family+lang; aliases hold a list of map ids to merge
const sharedMaps = {}
const mapIdsFor = (fam, langSet) => {
  const ids = []
  ;[...langSet].sort().forEach((lang) => {
    const found = paramData[lang] ? paramData[lang][fam] : null
    if (!found) {
      return
    }
    const id = `${fam}|${lang}`
    if (sharedMaps[id] === undefined) {
      const map = trimMap(found)
      sharedMaps[id] = Object.keys(map).length > 0 ? map : null
    }
    if (sharedMaps[id]) {
      ids.push(id)
    }
  })
  return ids
}

// what the previous build (or the hand-curated era) had, to report losses
const previousNames = async (file) => {
  const url = new URL(`${file}.js`, srcDir)
  if (!existsSync(url)) {
    return []
  }
  const mod = await import(url)
  return mod.default
}

const header = `// generated by plugins/i18n/scripts (${today()}) — do not edit; adjust scripts/overrides.js and re-run`
const paramMaps = {}
let total = 0

// settle every family's final names first, so include entries can't shadow a fetched one
const final = {}
famKeys.forEach((fam) => {
  final[fam] = [...all[fam].keys()].filter((name) => keepable(fam, name)).sort()
})
const owner = new Map()
famKeys.forEach((fam) => final[fam].forEach((name) => owner.set(name, fam)))

for (const fam of famKeys) {
  const file = families[fam].file
  const names = final[fam]
  names.forEach((name) => {
    const ids = mapIdsFor(fam, all[fam].get(name))
    if (ids.length > 0) {
      paramMaps[name] = ids
    }
  })
  const kept = (overrides.include[fam] || []).filter((name) => {
    if (names.includes(name)) {
      return false
    }
    if (owner.has(name)) {
      console.log(`⚠️  include '${name}' (${fam}) skipped — the fetch assigns it to ${owner.get(name)}`)
      return false
    }
    return true
  })
  const lost = (await previousNames(file)).filter((name) => names.includes(name) === false && kept.includes(name) === false)
  if (lost.length > 0) {
    console.log(`${fam}: not confirmed by fetch — ${lost.map((n) => `'${n}'`).join(', ')}`)
  }
  const lines = names.map((name) => {
    const langs = [...all[fam].get(name)].sort()
    const where = langs.length > 6 ? `${langs.length} wikis` : langs.join(' ')
    return `  '${esc(name)}', // ${where}`
  })
  kept.sort().forEach((name) => lines.push(`  '${esc(name)}', // kept by hand`))
  writeFileSync(new URL(`${file}.js`, srcDir), `${header}\nexport default [\n${lines.join('\n')}\n]\n`)
  total += lines.length
  console.log(`${fam.padEnd(20)} ${String(names.length).padStart(4)} fetched ${String(kept.length).padStart(3)} kept`)
}

// hand-written maps get their own id, listed first so they win on conflicts
Object.keys(overrides.params || {}).forEach((name) => {
  const id = `hand|${name}`
  sharedMaps[id] = overrides.params[name]
  paramMaps[name] = [id, ...(paramMaps[name] || [])]
})

const asMap = (map) =>
  `{ ${Object.keys(map)
    .map((key) => `'${esc(key)}': '${esc(map[key])}'`)
    .join(', ')} }`
const mapLines = Object.keys(sharedMaps)
  .filter((id) => sharedMaps[id])
  .sort()
  .map((id) => `    '${esc(id)}': ${asMap(sharedMaps[id])},`)
const aliasLines = Object.keys(paramMaps)
  .sort()
  .map((name) => `    '${esc(name)}': [${paramMaps[name].map((id) => `'${esc(id)}'`).join(', ')}],`)
const paramsFile = `${header}
// localized → english parameter names. \`maps\` holds one map per template+wiki;
// \`aliases\` lists which maps apply to each template alias, first match winning.
export default {
  maps: {
${mapLines.join('\n')}
  },
  aliases: {
${aliasLines.join('\n')}
  },
}
`
writeFileSync(new URL('params.js', srcDir), paramsFile)

console.log(`\n${total} template aliases, ${aliasLines.length} with param maps (${mapLines.length} shared maps), ${coreDrops} dropped as core collisions`)
